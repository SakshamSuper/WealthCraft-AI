def generate_weekly_nav_history(initial_nav, annual_return, volatility, weeks=260):
    nav_values = []
    current_nav = initial_nav
    dt_delta = 1.0 / 52.0
    
    today = datetime.utcnow().date()
    start_date = today - timedelta(weeks=weeks)
    
    mu = annual_return
    sigma = volatility
    
    for w in range(weeks + 1):
        date = start_date + timedelta(weeks=w)
        epsilon = random.normalvariate(0, 1)
        growth = (mu - 0.5 * sigma**2) * dt_delta + sigma * epsilon * (dt_delta**0.5)
        current_nav = current_nav * math.exp(growth)
        current_nav = max(1.0, current_nav)
        nav_values.append((date, round(current_nav, 4)))
        
    return nav_values

